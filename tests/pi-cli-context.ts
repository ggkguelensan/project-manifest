import { observePiCli } from './helpers/pi-cli-observation.ts';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

mkdirSync('e2e/tmp', { recursive: true });
const root = mkdtempSync(resolve('e2e/tmp/pi-cli-context-'));
const cwd = resolve(root, 'repository/target'), agentDir = resolve(root, 'agent');
for (const path of [cwd, agentDir, resolve(agentDir, 'skills/other'), resolve(root, 'selected')]) mkdirSync(path, { recursive: true });
execFileSync('git', ['init', '-q', resolve(root, 'repository')]);
const entry = resolve(cwd, 'AGENTS.md');
writeFileSync(entry, 'SELECTED_TARGET_RULE: inspect the selected application.\n');
writeFileSync(resolve(agentDir, 'SYSTEM.md'), 'UNSELECTED_SYSTEM_OVERRIDE\n');
writeFileSync(resolve(agentDir, 'APPEND_SYSTEM.md'), 'UNSELECTED_APPEND_OVERRIDE\n');
writeFileSync(resolve(agentDir, 'AGENTS.md'), 'UNSELECTED_GLOBAL_RULE\n');
writeFileSync(resolve(root, 'repository/AGENTS.md'), 'UNSELECTED_PARENT_RULE\n');
writeFileSync(resolve(agentDir, 'skills/other/SKILL.md'), '---\nname: unselected-cli-probe\ndescription: UNSELECTED_SKILL_METADATA\n---\nUNSELECTED_BODY\n');
const selected = resolve(root, 'selected');
writeFileSync(resolve(selected, 'SKILL.md'), '---\nname: selected-cli-probe\ndescription: SELECTED_SKILL_METADATA\n---\nSELECTED_BODY_DEFERRED\n');
const common = ['--offline', '--no-session', '--no-extensions', '--no-skills', '--no-prompt-templates', '--no-themes', '--no-context-files', '--skill', selected, '--tools', 'read', '--mode', 'rpc', '--approve'];
const run = (name: string, args: string[]) => observePiCli(cwd, args, agentDir, resolve(root, name));
const uncontrolled = run('negative-control', common);
assert.match(uncontrolled.prompt, /UNSELECTED_SYSTEM_OVERRIDE/);
const args = [...common, '--system-prompt', '', '--append-system-prompt', entry];
const observed = run('selected-context', args);
assert.match(observed.prompt, /SELECTED_TARGET_RULE/);
assert.match(observed.prompt, /SELECTED_SKILL_METADATA/);
assert.ok(!observed.prompt.includes('UNSELECTED_'));
assert.ok(!observed.prompt.includes('SELECTED_BODY_DEFERRED'));
assert.deepEqual(observed.tools, ['read']);
const proof = { version: execFileSync('pi', ['--version'], { encoding: 'utf8' }).trim(), kind: 'native-cli-session-start', cwd, arguments: args, agent_directory: agentDir, selected_skill: 'selected-cli-probe', instruction_files: [entry], tools: observed.tools, full_skill_body_loaded: false, prompt_sha256: createHash('sha256').update(observed.prompt).digest('hex'), model_calls: 0, negative_control: 'SYSTEM.md is loaded despite --no-context-files unless explicitly suppressed', limitations: ['Explicit diagnostic observer extension at session_start; no model request or skill execution.', 'Fixture agent directory; not a claim about arbitrary inherited user settings or mandatory policies.', 'Read tool selection is not filesystem isolation.'] };
writeFileSync(resolve(root, 'proof.json'), JSON.stringify(proof, null, 2) + '\n');
console.log(JSON.stringify({ root, ...proof }, null, 2));
