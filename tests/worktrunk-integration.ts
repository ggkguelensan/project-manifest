import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { planTask, readProject } from '../scripts/project.ts';

const git = (cwd: string, ...args: string[]) => execFileSync('git', ['-c', 'core.hooksPath=/dev/null', '-c', 'commit.gpgsign=false', ...args], { cwd, encoding: 'utf8', stdio: 'pipe' }).trim();
mkdirSync('e2e/tmp', { recursive: true });
const root = mkdtempSync(resolve('e2e/tmp/worktrunk-'));
const repo = resolve(root, 'repositories/frontend');
mkdirSync(resolve(repo, 'apps/web/e2e'), { recursive: true });
writeFileSync(resolve(repo, 'apps/web/e2e/.gitignore'), '/tmp/\n');
writeFileSync(resolve(repo, 'apps/web/version.txt'), 'release\n');
git(repo, 'init', '-b', 'dev'); git(repo, 'add', '.');
const commit = (message: string) => git(repo, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-am', message);
commit('Release fixture'); git(repo, 'branch', 'release-1.0.0');
const releaseCommit = git(repo, 'rev-parse', 'HEAD');
writeFileSync(resolve(repo, 'apps/web/version.txt'), 'development\n'); commit('Development diverges');
const developmentCommit = git(repo, 'rev-parse', 'HEAD');
const config = resolve(root, 'worktrunk.toml');
// The template belongs only to native configuration. Consume wt's returned path below.
writeFileSync(config, 'worktree-path = "{{ repo_path }}/../../tasks/{{ branch | sanitize }}"\n');
const definition = { schema_version: 1, project_id: 'wt-fixture', repositories: [{ id: 'frontend', path: 'repositories/frontend', references: [], development: 'dev', release: { kind: 'semver' } }], targets: [{ id: 'web', repository_id: 'frontend', path: 'apps/web', manifests: [] }], tools: { worktrunk: { enabled: true, required_for_tasks: true, config: 'worktrunk.toml' }, graphify: { enabled: false, procedure: null } }, manifests: [] };
const file = resolve(root, 'project.json'); writeFileSync(file, JSON.stringify(definition, null, 2));
const project = readProject(file, root);
const wt = (...args: string[]) => execFileSync('wt', ['--config', config, '-C', repo, ...args], { encoding: 'utf8', stdio: 'pipe', timeout: 30000 });
const native = JSON.parse(wt('switch', '--create', 'task/development', '--base', 'dev', '--no-hooks', '--no-cd', '--format', 'json'));
const select = (result: any, purpose: 'development' | 'release', release?: string) => {
  assert.equal(typeof result.path, 'string', 'wt must return a concrete worktree path');
  const selection = planTask(project, root, { target: 'web', worktree: relative(root, realpathSync(result.path)), purpose, release });
  assert.equal(selection.worktrunk.config, config);
  assert.ok(selection.worktrunk.version);
  assert.equal(selection.branch, result.branch);
  return selection;
};
const development = select(native, 'development');
assert.equal(development.revision, developmentCommit);
assert.equal(development.base_commit, developmentCommit);
assert.equal(readFileSync(resolve(development.target_root, 'version.txt'), 'utf8'), 'development\n');
const releaseNative = JSON.parse(wt('switch', '--create', 'task/release', '--base', 'release-1.0.0', '--no-hooks', '--no-cd', '--format', 'json'));
const release = select(releaseNative, 'release', 'release-1.0.0');
assert.equal(release.revision, releaseCommit);
assert.equal(release.base_commit, releaseCommit);
assert.notEqual(release.revision, development.revision);
assert.equal(readFileSync(resolve(release.target_root, 'version.txt'), 'utf8'), 'release\n');
assert.throws(() => select(releaseNative, 'release'), /concrete release branch/);
assert.throws(() => planTask(project, root, { target: 'web', worktree: 'repositories/frontend', purpose: 'development' }), /main working clone/);
const worktreesBefore = git(repo, 'worktree', 'list', '--porcelain');
assert.throws(() => wt('switch', '--create', 'task/invalid', '--base', 'absent-base', '--no-hooks', '--no-cd', '--format', 'json'));
assert.equal(git(repo, 'worktree', 'list', '--porcelain'), worktreesBefore, 'Failed creation must not select/create another checkout');
// Changing configuration must not relocate an existing worktree or make the caller reconstruct its path.
writeFileSync(config, 'worktree-path = "{{ repo_path }}/../../other-tasks/{{ branch | sanitize }}"\n');
const reused = JSON.parse(wt('switch', 'task/development', '--no-hooks', '--no-cd', '--format', 'json'));
assert.equal(realpathSync(reused.path), development.worktree);
assert.equal(select(reused, 'development').revision, developmentCommit);
for (const path of [repo, development.worktree, release.worktree]) assert.equal(git(path, 'status', '--porcelain'), '');
const proof = { version: wt('--version').trim(), project_definition: file, config, native_results: { development: native, release: releaseNative, reused }, selections: { development, release }, checks: ['native config owns path template', 'explicit distinct development and release bases', 'concrete release required', 'main clone rejected', 'missing base preserves worktree inventory', 'existing worktree reused despite changed template', 'source checkouts unchanged'], limitations: ['Isolated local fixture; hooks intentionally disabled, no lifecycle hook or remote operation tested.', 'Selection inspects Git and wt availability; historical creation via wt is proven here by native command results, not inferred for arbitrary worktrees.'] };
const output = resolve(development.target_root, 'e2e/tmp/worktrunk-verification.json'); mkdirSync(resolve(development.target_root, 'e2e/tmp'), { recursive: true });
writeFileSync(output, JSON.stringify(proof, null, 2) + '\n');
console.log(JSON.stringify({ root, proof: output, version: proof.version, checks: proof.checks }, null, 2));
